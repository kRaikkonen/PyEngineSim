"""Generate core/sound/src/nozzle_fit.rs: the nozzle flow function without a power.

The compressible orifice of the v2 core (core/sound/src/gas.rs) is

    psi(r, g)^2 = 2g/(g-1) * (r^(2/g) - r^((g+1)/g))        r = p_dn / p_up

and it is the innermost function of the whole sound model -- evaluated a few
times per open valve per sample.  Written with x = 1 - r,

    psi^2 = 2 x Q(x, g),      Q -> 1 as x -> 0

Q is smooth (analytic) in both x and g, so a polynomial holds it to rounding
error: this script fits Q on x in [0, 0.5] (the critical ratio is at x = 0.42
.. 0.47) and g in [1.10, 1.45], and the critical ratio r_crit(g) itself, by
interpolation at Chebyshev nodes, and writes the coefficients as Rust
constants.  The Rust tests hold the fit against the formula above.

    python tools/gen_nozzle_fit.py            # rewrite the file
    python tools/gen_nozzle_fit.py --check    # fail if the file is stale
"""
import io
import os
import sys

import numpy as np
from numpy.polynomial import chebyshev as C

X_MAX = 0.5
G_LO, G_HI = 1.10, 1.45
NX, NG = 10, 6          # degrees in x and in gamma
NR = 8                  # degree of r_crit(gamma)

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                   "..", "core", "sound", "src", "nozzle_fit.rs")


def q_exact(x, g):
    """psi^2 / (2x), without the cancellation at small x."""
    x = np.asarray(x, dtype=float)
    a = 1.0 / g
    r = 1.0 - x
    k = 2.0 * g / (g - 1.0)
    # r^(2/g) - r^(1+1/g) = r^(2/g) * (1 - r^(1-1/g)) = -r^(2a) * expm1((1-a) log1p(-x))
    num = -np.power(r, 2.0 * a) * np.expm1((1.0 - a) * np.log1p(-x))
    return k * num / (2.0 * x)


def r_crit(g):
    return np.power(2.0 / (g + 1.0), g / (g - 1.0))


def nodes(n):
    """n Chebyshev-Gauss nodes on (-1, 1)."""
    k = np.arange(n)
    return np.cos(np.pi * (k + 0.5) / n)


def fit():
    u = nodes(NX + 1)
    v = nodes(NG + 1)
    x = 0.5 * X_MAX * (u + 1.0)
    g = 0.5 * (G_LO + G_HI) + 0.5 * (G_HI - G_LO) * v
    f = np.array([[q_exact(xi, gj) for gj in g] for xi in x])
    # Chebyshev coefficients by the two discrete transforms, then to powers
    # of u and v (degree <= 13 on [-1, 1]: well conditioned)
    cu = C.chebfit(u, f, NX)                    # (NX+1, NG+1): along x, per gamma
    cuv = C.chebfit(v, cu.T, NG)                # (NG+1, NX+1): [j][i]
    mono = np.zeros((NX + 1, NG + 1))
    for j in range(NG + 1):
        for i in range(NX + 1):
            # T_i(u) T_j(v) -> monomials
            pu = C.cheb2poly(np.eye(NX + 1)[i])
            pv = C.cheb2poly(np.eye(NG + 1)[j])
            mono[:len(pu), :len(pv)] += cuv[j, i] * np.outer(pu, pv)

    vr = nodes(NR + 1)
    gr = 0.5 * (G_LO + G_HI) + 0.5 * (G_HI - G_LO) * vr
    rc = C.cheb2poly(C.chebfit(vr, r_crit(gr), NR))
    rc = np.concatenate([rc, np.zeros(NR + 1 - len(rc))])
    return mono, rc


def evaluate(mono, x, g):
    u = 2.0 * x / X_MAX - 1.0
    v = (g - 0.5 * (G_LO + G_HI)) / (0.5 * (G_HI - G_LO))
    c = np.zeros(NX + 1)
    for j in range(NG, -1, -1):
        c = c * v + mono[:, j]
    q = 0.0
    for i in range(NX, -1, -1):
        q = q * u + c[i]
    return q


def errors(mono, rc):
    worst_q = 0.0
    worst_r = 0.0
    for g in np.linspace(G_LO, G_HI, 141):
        xs = np.concatenate([np.linspace(1e-9, 1e-3, 50), np.linspace(1e-3, X_MAX, 600)])
        for x in xs:
            worst_q = max(worst_q, abs(evaluate(mono, x, g) / q_exact(x, g) - 1.0))
        v = (g - 0.5 * (G_LO + G_HI)) / (0.5 * (G_HI - G_LO))
        r = 0.0
        for j in range(NR, -1, -1):
            r = r * v + rc[j]
        worst_r = max(worst_r, abs(r / r_crit(g) - 1.0))
    return worst_q, worst_r


def rust(mono, rc, eq, er):
    def num(v):
        return repr(float(v))
    out = []
    out.append("//! GENERATED by tools/gen_nozzle_fit.py -- do not edit.")
    out.append("//!")
    out.append("//! The nozzle flow function as a polynomial: psi^2 = 2 x Q(x, gamma), x = 1 - r.")
    out.append("//! Q in powers of u = 2x/X_MAX - 1 and v = (gamma - G_MID)/G_HALF; `Q[i][j]`")
    out.append("//! multiplies u^i v^j.  `R_CRIT[j]` multiplies v^j in the critical ratio.")
    out.append("//! Worst relative error against the exact law over the fitted rectangle:")
    out.append("//! Q %.1e, r_crit %.1e." % (eq, er))
    out.append("")
    out.append("pub const X_MAX: f64 = %s;" % num(X_MAX))
    out.append("pub const G_LO: f64 = %s;" % num(G_LO))
    out.append("pub const G_HI: f64 = %s;" % num(G_HI))
    out.append("pub const G_MID: f64 = %s;" % num(0.5 * (G_LO + G_HI)))
    out.append("pub const G_HALF: f64 = %s;" % num(0.5 * (G_HI - G_LO)))
    out.append("pub const NX: usize = %d;" % NX)
    out.append("pub const NG: usize = %d;" % NG)
    out.append("pub const NR: usize = %d;" % NR)
    out.append("")
    out.append("#[rustfmt::skip]")
    out.append("pub const Q: [[f64; NG + 1]; NX + 1] = [")
    for i in range(NX + 1):
        out.append("    [" + ", ".join(num(mono[i, j]) for j in range(NG + 1)) + "],")
    out.append("];")
    out.append("")
    out.append("#[rustfmt::skip]")
    out.append("pub const R_CRIT: [f64; NR + 1] = [")
    out.append("    " + ", ".join(num(c) for c in rc) + ",")
    out.append("];")
    out.append("")
    return "\n".join(out)


def main():
    mono, rc = fit()
    eq, er = errors(mono, rc)
    text = rust(mono, rc, eq, er)
    print("Q: degree %d x %d, worst relative error %.2e;  r_crit: degree %d, %.2e"
          % (NX, NG, eq, NR, er))
    if "--check" in sys.argv:
        have = io.open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if have != text:
            print("STALE: %s does not match this script" % os.path.normpath(OUT))
            sys.exit(1)
        print("up to date")
        return
    io.open(OUT, "w", encoding="utf-8", newline="\n").write(text)
    print("wrote", os.path.normpath(OUT))


if __name__ == "__main__":
    main()
